// Regenerate only after verifying the source Word template in a real document reader.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const definitions = [
  ['Didarian_Research_Template.doc', 'application/msword'],
  [
    'Didarian_Research_Template.docx',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  ],
  ['Didarian_Research_Template.tex', 'application/x-tex'],
];
const resources = [];
for (const [filename, contentType] of definitions) {
  const bytes = await readFile(resolve(root, 'public/resources', filename));
  if (filename.endsWith('.doc') && bytes.subarray(0, 8).toString('hex') !== 'd0cf11e0a1b11ae1')
    throw new Error('The DOC is not Compound File Binary.');
  resources.push({
    filename,
    contentType,
    byteSize: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    base64: bytes.toString('base64'),
  });
}
const output = resolve(root, 'supabase/functions/provision-resources');
await mkdir(output, { recursive: true });
await writeFile(
  resolve(output, 'assets.ts'),
  `// Generated by scripts/build-resource-payload.mjs from verified public resources.\n// Only these compile-time assets can be published by this function. No secrets.\nexport const resources = ${JSON.stringify(resources, null, 2)} as const;\n`,
);
console.log(`Embedded ${resources.length} known verified resource assets.`);
